"""Report patches installed in this process's real vLLM environment."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools._common import PatchEnvironmentError, load_patch_records  # noqa: E402


def _cell(value: str) -> str:
    return (
        value.strip().replace("|", "&#124;").replace("\r\n", "\n").replace("\n", "<br>")
    )


def render(records: list[Any]) -> str:
    """Render a stable report; installed records do not enumerate every path."""
    lines = [
        "# Runtime patch manifest",
        "",
        "Generated by `python tools/patch_manifest.py` from actual installation results.",
        "This process and environment do not cover every conditional platform path.",
        "",
        "| Target | Kind | Reason | Affected versions | Remove when |",
        "|---|---|---|---|---|",
    ]
    for record in sorted(records, key=lambda item: item.target):
        lines.append(
            "| "
            + " | ".join(
                _cell(value)
                for value in (
                    record.target,
                    record.kind,
                    record.reason,
                    record.affected_versions,
                    record.remove_when,
                )
            )
            + " |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        help="save the report to this explicit path (default: stdout)",
    )
    args = parser.parse_args(argv)
    try:
        records = load_patch_records("patch manifest")
        expected = render(records)
    except PatchEnvironmentError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    if args.output is None:
        print(expected, end="")
    else:
        try:
            args.output.write_text(expected, encoding="utf-8")
        except OSError as exc:
            print(
                f"ERROR: cannot write report to {args.output}: {exc}", file=sys.stderr
            )
            return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
