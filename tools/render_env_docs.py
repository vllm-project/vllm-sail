"""Generate or check the runtime environment variable reference document."""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from vllm_sail import envs  # noqa: E402

DEFAULT_OUTPUT = ROOT / "docs" / "user_guide" / "environment_variables.md"
REGENERATE_COMMAND = "python tools/render_env_docs.py"
CHECK_COMMAND = "python tools/render_env_docs.py --check"


def _cell(value: str) -> str:
    return (
        value.strip().replace("|", "&#124;").replace("\r\n", "\n").replace("\n", "<br>")
    )


def _format_default(spec: envs.EnvSpec) -> str:
    if spec.default_display is not None:
        return spec.default_display
    if spec.kind == "bool":
        return "`1`" if spec.default else "`0`"
    if spec.default is None:
        return "Unset (automatic)"
    return f"`{spec.default}`"


def _format_values(spec: envs.EnvSpec) -> str:
    if spec.kind == "bool":
        return "`0`, `1`"
    if spec.kind == "choice":
        return ", ".join(f"`{choice}`" for choice in spec.choices)
    if spec.kind == "positive_int":
        return "positive integer"
    if spec.kind == "int":
        return "integer"
    if spec.kind == "sha1_commit":
        return "40-hex commit SHA"
    return "path" if spec.name == "PPU_SDK" else "string"


def _format_aliases(spec: envs.EnvSpec) -> str:
    if not spec.aliases:
        return "—"
    return ", ".join(f"`{alias}`" for alias in spec.aliases)


def render(specs: Sequence[envs.EnvSpec] | None = None) -> str:
    """Render the runtime environment variable reference markdown."""
    items = envs.ENVIRONMENT_SPECS if specs is None else specs
    sections: dict[str, list[envs.EnvSpec]] = {}
    for spec in items:
        sections.setdefault(spec.section, []).append(spec)

    lines = [
        f"<!-- Generated by `{REGENERATE_COMMAND}`. Do not edit manually. -->",
        "",
        "# Runtime Environment Variables",
        "",
        "This reference is generated from [`vllm_sail/envs.py`](../../vllm_sail/envs.py).",
        "For workflow guidance, backend interaction rules and model-specific constraints,",
        "see [Configuration](configuration.md). For build-time settings, see",
        "[HGGC kernels](../developer_guide/kernels.md#build-settings).",
        "",
        "## Resolution rules",
        "",
        "- Every `VLLM_SAIL_*` variable accepts the corresponding `VLLM_PPU_*` alias for",
        "  compatibility. The canonical `VLLM_SAIL_*` name always takes precedence when",
        "  set, including `0` or an empty string.",
        "- Shared or upstream names without `VLLM_SAIL_*` prefixes keep their own names",
        "  and have no `VLLM_PPU_*` aliases.",
        "- Boolean truthy values are `true`, `1`, `yes` and `on` (case-insensitive);",
        "  an empty boolean is false, and an empty choice or integer uses its default.",
        "- Regenerate or verify this file:",
        "",
        "```bash",
        REGENERATE_COMMAND,
        CHECK_COMMAND,
        "```",
    ]

    for section, group in sections.items():
        lines.extend(
            [
                "",
                f"## {section}",
                "",
                "| Variable | Default | Values | Aliases | Description |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
        for spec in group:
            row = (
                f"`{spec.name}`",
                _format_default(spec),
                _format_values(spec),
                _format_aliases(spec),
                spec.description,
            )
            lines.append("| " + " | ".join(_cell(col) for col in row) + " |")

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        default=str(DEFAULT_OUTPUT),
        help=(
            "output markdown path, or '-' for stdout "
            "(default: docs/user_guide/environment_variables.md)"
        ),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the output file matches the freshly rendered document",
    )
    args = parser.parse_args(argv)

    expected = render()
    if args.check:
        if args.output == "-":
            print("ERROR: --check cannot be used with --output -", file=sys.stderr)
            return 2
        target = Path(args.output)
        if not target.is_file():
            print(
                f"ERROR: {target} does not exist; generate it with `{REGENERATE_COMMAND}`",
                file=sys.stderr,
            )
            return 1
        actual = target.read_text(encoding="utf-8")
        if actual != expected:
            print(
                f"ERROR: {target} is out of date; regenerate it with `{REGENERATE_COMMAND}`",
                file=sys.stderr,
            )
            return 1
        print(f"{target} matches vllm_sail/envs.py")
        return 0

    if args.output == "-":
        print(expected, end="")
        return 0

    target = Path(args.output)
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8")
    except OSError as exc:
        print(f"ERROR: cannot write {target}: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
